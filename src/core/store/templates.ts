/** 模板 → 落盘内容：替换 {书名} 占位并统一 CRLF（既有磁盘格式） */
export function renderTemplate(content: string, bookName: string): string {
  return content.replace(/\{书名\}/g, bookName).replace(/\r?\n/g, "\r\n");
}
